const MAX_TAG_LENGTH = 20;
const MAX_TAGS = 13;
const MAX_TITLE_WORDS = 15;

export function normalizeEtsyTags(tags) {
  const seen = new Set();
  const cleaned = [];
  for (const raw of tags) {
    const tag = raw.trim().toLowerCase().slice(0, MAX_TAG_LENGTH);
    if (!tag || seen.has(tag)) continue;
    seen.add(tag);
    cleaned.push(tag);
    if (cleaned.length >= MAX_TAGS) break;
  }
  while (cleaned.length < MAX_TAGS) {
    const filler = "broke dads club";
    if (!seen.has(filler)) {
      cleaned.push(filler);
      seen.add(filler);
    } else break;
  }
  return cleaned;
}

export function normalizeEtsyTitle(title) {
  const words = title.trim().split(/\s+/).filter(Boolean);
  if (words.length <= MAX_TITLE_WORDS) return title.trim();
  return words.slice(0, MAX_TITLE_WORDS).join(" ");
}

