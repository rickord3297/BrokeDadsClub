/** Match Etsy row back to website source product id via results map or title. */
export function resolveSourceId(etsyProduct, publishedMap, websiteByTitle) {
  for (const [sourceId, row] of Object.entries(publishedMap ?? {})) {
    if (row.etsyProductId === etsyProduct.id) return sourceId;
  }
  const byTitle = ETSY_TITLE_TO_SOURCE_ID[etsyProduct.title];
  if (byTitle) return byTitle;
  const website = websiteByTitle?.get(etsyProduct.title);
  return website?.id ?? null;
}

export function etsyListingCopyForSource(sourceId) {
  const copy = ETSY_LISTING_COPY_BY_SOURCE_ID[sourceId];
  if (!copy) return null;
  return {
    title: normalizeEtsyTitle(copy.title),
    description: copy.description.trim(),
    tags: normalizeEtsyTags(copy.tags),
  };
}
